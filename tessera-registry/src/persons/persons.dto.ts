import { ApiProperty, ApiPropertyOptional } from "@nestjs/swagger";
import { Type } from "class-transformer";
import { IsDate, IsEnum, IsNotEmpty, IsOptional, IsString, MaxDate } from "class-validator";
import { Gender, PersonStatus } from "../generated/prisma/enums.js";

/* Data coming from the request body.
 * status, createdAt and updatedAt are set by the server, so the client can't send them. */

export class CreatePersonDto {
  @ApiProperty({ example: 'Ada' })
  @IsString()
  @IsNotEmpty()
  givenName: string;

  @ApiProperty({ example: 'Okafor' })
  @IsString()
  @IsNotEmpty()
  familyName: string;

  @ApiProperty({
    type: String,
    format: 'date',
    example: '1990-05-14',
    description: 'Must not be in the future',
  })
  @Type(() => Date) /* "1990-05-17" in the request becomes a real Date */
  @IsDate()
  @MaxDate(() => new Date(), {
    message: 'dateOfBirth must not be in the future',
  })/* worked out on every request, so "now" is always today */
  dateOfBirth: Date;

  @ApiPropertyOptional({ enum: Gender, example: Gender.female })
  @IsEnum(Gender)
  @IsOptional()
  gender?: Gender;
}

/* What the API sends back for a person. Documentation only: nothing validates it. */
export class PersonResponseDto {
  @ApiProperty({ example: '3f2b8c1e-6d4a-4f7e-9b2c-1a5d7e9f0c3b' })
  id: string;

  @ApiProperty({ example: '284190637524', description: '11 random digits + 1 Verhoeff check digit, generated by the server' })
  nationalId: string;

  @ApiProperty({ example: 'Ada' })
  givenName: string;

  @ApiProperty({ example: 'Okafor' })
  familyName: string;

  @ApiProperty({ example: '1990-05-14T00:00:00.000Z' })
  dateOfBirth: Date;

  @ApiPropertyOptional({ enum: Gender, example: Gender.female, nullable: true })
  gender: Gender | null;

  @ApiProperty({ enum: PersonStatus, example: PersonStatus.active })
  status: PersonStatus;

  @ApiProperty({ example: '2026-10-28T19:04:51.000Z' })
  createdAt: Date;

  @ApiProperty({ example: '2026-10-28T19:04:51.000Z' })
  updatedAt: Date;
}
