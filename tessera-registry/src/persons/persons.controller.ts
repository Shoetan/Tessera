import { Body, Controller, Get, Param, Query, Post, Patch, HttpCode } from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiCreatedResponse,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiQuery,
  ApiTags,
} from '@nestjs/swagger';
import { CreatePersonDto, DeactivatePersonDto, PersonResponseDto, UpdatePersonDto } from './persons.dto.js';
import { PersonsService } from './persons.service.js';
import { ErrorResponseDto } from '../common/dto/error-response.dto.js';
import { AuditHistoryResponseDto } from '../audit/audit.dto.js';
import { CursorPaginationQueryDto, DEFAULT_PAGE_LIMIT, MAX_PAGE_LIMIT } from '../common/dto/pagination.dto.js';

@ApiTags('persons')
@Controller('persons')
export class PersonsController {
  constructor(private readonly personsService: PersonsService) {}

  @Post()
  @ApiOperation({
    summary: 'Register a person; the national ID is generated by the server',
  })
  @ApiCreatedResponse({ type: PersonResponseDto })
  @ApiBadRequestResponse({
    type: ErrorResponseDto,
    description:
      'Missing name, date of birth in the future, unrecognised gender, or a nationalId was sent',
  })
  registerPerson(@Body() createPersonDto: CreatePersonDto) {
    return this.personsService.registerPerson(createPersonDto, 'system');
  }

  @Get(':id')
  @ApiOperation({
    summary: 'Read one person by their internal id (never by national ID)',
  })
  @ApiParam({ name: 'id', example: '3f2b8c1e-6d4a-4f7e-9b2c-1a5d7e9f0c3b' })
  @ApiOkResponse({ type: PersonResponseDto })
  @ApiNotFoundResponse({
    type: ErrorResponseDto,
    description: 'No person has this id',
  })
  findPersonById(@Param('id') id: string) {
    return this.personsService.findPersonById(id);
  }

  @Patch(':id')
  @ApiOperation({
    summary: 'Update a person by their internal id (never by national ID)',
  })
  @ApiParam({ name: 'id', example: '3f2b8c1e-6d4a-4f7e-9b2c-1a5d7e9f0c3b' })
  @ApiOkResponse({ type: PersonResponseDto })
  @ApiNotFoundResponse({
    type: ErrorResponseDto,
    description: 'No person has this id',
  })
  @ApiBadRequestResponse({
    type: ErrorResponseDto,
    description:
      'Missing name, date of birth in the future, unrecognised gender, or a nationalId was sent',
  })
  updatePerson(
    @Param('id') id: string,
    @Body() updatePersonDto: UpdatePersonDto,
  ) {
    return this.personsService.updatePerson(id, updatePersonDto, 'system');
  }

  @HttpCode(200)
  @Post(':id/deactivate')
  deactivatePerson(
    @Param('id') id: string,
    @Body() deactivatePersonDto: DeactivatePersonDto,
  ) {
    return this.personsService.deactivatePerson(
      id,
      deactivatePersonDto,
      'system',
    );
  }

  @Get(':id/audit')
  @ApiOperation({
    summary: "A person's full change history, oldest first.",
  })
  @ApiParam({ name: 'id', example: '3f2b8c1e-6d4a-4f7e-9b2c-1a5d7e9f0c3b' })
  @ApiQuery({
    name: 'limit',
    required: false,
    type: Number,
    description: `Max entries to return, 1-${MAX_PAGE_LIMIT}`,
    example: DEFAULT_PAGE_LIMIT,
  })
  @ApiQuery({
    name: 'cursor',
    required: false,
    type: String,
    description: 'The nextCursor from a previous page, to fetch the page after it',
    example: '9a1c4e2b-7f3d-4b8a-a6e1-2d5c8f0b3e74',
  })
  @ApiOkResponse({ type: AuditHistoryResponseDto })
  @ApiNotFoundResponse({
    type: ErrorResponseDto,
    description: 'No person has this id',
  })
  async fetchPersonAuditHistory(@Param('id') id: string, @Query() query: CursorPaginationQueryDto) {
    return this.personsService.getAuditHistory(id, query.limit, query.cursor);
  }
}
