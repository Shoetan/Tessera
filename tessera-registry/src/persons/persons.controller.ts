import { Body, Controller, Get, Param, Post } from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiCreatedResponse,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
} from '@nestjs/swagger';
import { CreatePersonDto, PersonResponseDto } from './persons.dto.js';
import { PersonsService } from './persons.service.js';
import { ErrorResponseDto } from '../common/dto/error-response.dto.js';

@ApiTags('persons')
@Controller('persons')
export class PersonsController {
  constructor(private readonly personsService:PersonsService) {}

  
  @Post() 
  @ApiOperation({ summary: 'Register a person; the national ID is generated by the server' })
  @ApiCreatedResponse({ type: PersonResponseDto })
  @ApiBadRequestResponse({
    type: ErrorResponseDto,
    description: 'Missing name, date of birth in the future, unrecognised gender, or a nationalId was sent',
  })
  registerPerson( @Body() createPersonDto:CreatePersonDto){
    return this.personsService.registerPerson(createPersonDto, 'system');

  }


  @Get(':id')
  @ApiOperation({ summary: 'Read one person by their internal id (never by national ID)' })
  @ApiParam({ name: 'id', example: '3f2b8c1e-6d4a-4f7e-9b2c-1a5d7e9f0c3b' })
  @ApiOkResponse({ type: PersonResponseDto })
  @ApiNotFoundResponse({ type: ErrorResponseDto, description: 'No person has this id' })
  findPersonById( @Param('id') id: string){
    return this.personsService.findPersonById(id);
  }


}
